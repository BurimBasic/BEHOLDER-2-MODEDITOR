 internal static void Verify(){
  var root=Path.GetDirectoryName(Application.dataPath);
  var ids=new HashSet<int>();
  foreach(var name in new[]{"TutorialHemnitz","HemnitzStory"}){
   var asset=Resources.FindObjectsOfTypeAll<TextAsset>().FirstOrDefault(t=>t.name==name);
   if(asset==null)throw new Exception("Prologue asset not loaded: "+name);
   if(asset.text!=File.ReadAllText(Path.Combine(root,name+".json")))throw new Exception("Original Ink graph changed: "+name);
   foreach(Match m in Regex.Matches(asset.text,@"\$(\d+)"))ids.Add(int.Parse(m.Groups[1].Value));
  }
  foreach(var pair in Text){if(Localization.Get(pair.Key)!=pair.Value)throw new Exception("Localization mismatch "+pair.Key);}
  var rows=ids.OrderBy(x=>x).Select(id=>id+"\t"+Localization.Get("$"+id)).ToArray();
  File.WriteAllLines(Path.Combine(root,"prologue-verified.txt"),rows);
  FloorAdmin.Log("PASS PROLOGUE localization="+Text.Count+" referenced="+ids.Count+" original Ink graphs unchanged; physical tutorial not replayed");
 }
